-- rhi-cpp -- the extracted render-hardware-interface library.
--
-- rhi ships a CMake build, but unlike SDL2/openal-soft it is a small, flat set
-- of translation units with no feature probing: everything CMake would decide
-- is a literal in cmake/sources/*.cmake plus a configure_file() of
-- include/rhi/Config.h.in. Reimplementing that in premake is a dozen lines and
-- avoids a second toolchain in the build (which for a *static* lib compiled
-- into the same binary as HPL2 also avoids ABI skew between the two).
--
-- The Vulkan dependency set (volk, VMA, Vulkan-Headers) is the engine's own --
-- rhi is explicitly designed for that (see rhi's cmake/Dependencies.cmake:
-- "the target already exists in this CMake tree -> use it, fetch nothing").
--
-- Location: --rhi-dir=<path>, else HPL2/extern/rhi, else a sibling rhi-cpp
-- checkout next to this repo.

local function resolve_rhi_dir()
    local explicit = _OPTIONS["rhi-dir"]
    if explicit and explicit ~= "" then return path.getabsolute(explicit) end
    local vendored = ROOT .. "/HPL2/extern/rhi"
    if os.isfile(vendored .. "/include/rhi/Rhi.h") then return vendored end
    local sibling = path.getabsolute(ROOT .. "/../rhi-cpp")
    if os.isfile(sibling .. "/include/rhi/Rhi.h") then return sibling end
    error("rhi: cannot find rhi-cpp. Pass --rhi-dir=<path>, or check it out at "
        .. vendored .. " or " .. sibling)
end

RHI_DIR = resolve_rhi_dir()

-- Where the generated rhi/Config.h lands. Mirrors CMake's
-- ${CMAKE_CURRENT_BINARY_DIR}/generated/rhi/Config.h.
RHI_GENERATED_DIR = ROOT .. "/build-premake/generated"

-- Values CMake would take from cache variables. Kept equal to the numbers the
-- engine used to spell in HPL2/core/include/graphics/HPLGraphicsConfig.h, which
-- rhi/Config.h replaces.
local RHI_CONFIG = {
    RHI_BACKEND_VULKAN    = 1,
    RHI_BACKEND_METAL     = 0,
    RHI_ENABLE_RAYTRACING = 1,
    RHI_FRAMES_IN_FLIGHT  = 2,
    RHI_SUB_COMMANDS      = 16,
    RHI_FRAME_SEGMENTS    = 6,
}

-- configure_file() equivalent, run at premake-generation time.
local function generate_rhi_config()
    os.mkdir(RHI_GENERATED_DIR .. "/rhi")
    local out = RHI_GENERATED_DIR .. "/rhi/Config.h"
    local text = table.concat({
        "// Generated by premake/deps/rhi.lua from rhi's include/rhi/Config.h.in.",
        "// Do not edit -- regenerate by re-running premake5.",
        "#ifndef RHI_CONFIG_H",
        "#define RHI_CONFIG_H",
        "",
        "#define RHI_VERSION_MAJOR 0",
        "#define RHI_VERSION_MINOR 1",
        "#define RHI_VERSION_PATCH 0",
        "#define RHI_VERSION_STRING \"0.1.0\"",
        "",
        "#define RHI_BACKEND_VULKAN "    .. RHI_CONFIG.RHI_BACKEND_VULKAN,
        "#define RHI_BACKEND_METAL "     .. RHI_CONFIG.RHI_BACKEND_METAL,
        "#define RHI_ENABLE_RAYTRACING " .. RHI_CONFIG.RHI_ENABLE_RAYTRACING,
        "",
        "#define RHI_FRAMES_IN_FLIGHT "  .. RHI_CONFIG.RHI_FRAMES_IN_FLIGHT,
        "#define RHI_SUB_COMMANDS "      .. RHI_CONFIG.RHI_SUB_COMMANDS,
        "#define RHI_FRAME_SEGMENTS "    .. RHI_CONFIG.RHI_FRAME_SEGMENTS,
        "",
        "#endif // RHI_CONFIG_H",
        "",
    }, "\n")
    -- Only rewrite when the content actually changes, so re-running premake
    -- does not invalidate every object that includes it.
    local existing = os.isfile(out) and io.readfile(out) or nil
    if existing ~= text then io.writefile(out, text) end
end

generate_rhi_config()

-- rhi's public headers are consumed with -fno-strict-aliasing (the backend
-- `union { vk; mtl; }` members are punned through). premake5.lua already sets
-- that workspace-wide for gcc/clang, so consumers inherit it.
function link_rhi()
    includedirs {
        RHI_DIR .. "/include",
        RHI_GENERATED_DIR,
    }
    -- rhi's Preamble.h includes <volk.h> and <vk_mem_alloc.h> directly.
    vulkan_includes()
    defines {
        "VMA_STATIC_VULKAN_FUNCTIONS=0",
        "VMA_DYNAMIC_VULKAN_FUNCTIONS=1",
    }
    links { "rhi" }
end

