        "VMA_STATIC_VULKAN_FUNCTIONS=0",
        "VMA_DYNAMIC_VULKAN_FUNCTIONS=1",
    }

    filter "toolset:gcc or clang"
        exceptionhandling "Off"   -- match HPL2 (-fno-exceptions); rhi throws nothing
    filter "system:linux"
        links { "dl" }
    filter {}

